#!/usr/bin/env python3
"""
Direct test of H2: frozen circuit against frozen random Fourier features, seed-paired.

    python make_h2_direct.py results/all_runs.csv --out-dir .

Both blocks are frozen replacements of the trained circuit in the main configuration of each
dataset (campaign "isolation"). Delta = frozen circuit minus frozen RFF, in percentage points.
The contrast is not part of the Holm family of build_tables.py, so the p-value is uncorrected.
Writes h2_numbers.tex (macros) and prints the three rows.
"""
import argparse, math, os, re
import numpy as np, pandas as pd
from scipy import stats

FULL = {"overhead": "overhead_adaptive", "sat6": "sat6", "so2sat": "so2sat_adaptive"}
SLUG = {"overhead": "overhead", "sat6": "sat", "so2sat": "sosat"}
MARGIN = 1.0


def macro(k, v):
    k = re.sub(r"[^A-Za-z]", "", k)
    return f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}\n"


def ptext(p):
    return "{<}\\,0.001" if p < 0.001 else f"{{=}}\\,{p:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("runs"); ap.add_argument("--out-dir", default=".")
    a = ap.parse_args()
    R = pd.read_csv(a.runs)
    R = R[R.campaign == "isolation"]
    mac = ["% generated by make_h2_direct.py; do not edit\n"]
    nequiv, tmax, res = 0, 0.0, {}
    for ds, cfg in FULL.items():
        q = R[R.config == f"{cfg}__frozen_quantum"].set_index("seed").test_acc
        r = R[R.config == f"{cfg}__frozen_rff"].set_index("seed").test_acc
        seeds = sorted(set(q.index) & set(r.index))
        assert len(seeds) == 10, f"{ds}: {len(seeds)} paired seeds"
        d = (q.loc[seeds] - r.loc[seeds]).to_numpy(float)
        n = len(d); se = d.std(ddof=1) / math.sqrt(n); tc = stats.t.ppf(0.975, n - 1)
        pt = float(stats.ttest_1samp(d, 0).pvalue)
        tost = max(stats.t.sf((d.mean() + MARGIN) / se, n - 1), stats.t.cdf((d.mean() - MARGIN) / se, n - 1))
        nequiv += tost < 0.05
        res[ds] = dict(tost=tost)
        if tost < 0.05:
            tmax = max(tmax, tost)
        s = SLUG[ds]
        mac += [macro(f"hdirect{s}delta", f"{d.mean():+.2f}"), macro(f"hdirect{s}lo", f"{d.mean() - tc * se:+.2f}"),
                macro(f"hdirect{s}hi", f"{d.mean() + tc * se:+.2f}"), macro(f"hdirect{s}p", ptext(pt)),
                macro(f"hdirect{s}tost", ptext(tost))]
        print(f"{ds:9s} delta={d.mean():+.2f} [{d.mean() - tc * se:+.2f}, {d.mean() + tc * se:+.2f}] p_t={pt:.3f} tost1={tost:.3f}")
    equiv = {ds for ds in FULL if "tost" in res[ds] and res[ds]["tost"] < 0.05}
    assert equiv == {"sat6", "so2sat"}, f"the text names SAT-6 and So2Sat as equivalent; data give {sorted(equiv)}"
    mac += [macro("hdirectnequiv", str(int(nequiv))), macro("hdirecttostmax", ptext(tmax))]
    os.makedirs(a.out_dir, exist_ok=True)
    open(os.path.join(a.out_dir, "h2_numbers.tex"), "w").writelines(mac)


if __name__ == "__main__":
    main()
